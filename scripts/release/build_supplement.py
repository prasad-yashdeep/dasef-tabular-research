#!/usr/bin/env python
"""Build the DMLR supplementary archive (one self-contained zip, must stay under 100 MB).

Included: code (src, scripts, configs, tests, pyproject, lockfile, README, LICENSE), every cached LLM schema,
prompt and raw response (cache/schemas*), every per-run results.json / schema.normalized.json / dataset_summary.json
(core, expansion, post-cutoff, anonymized, random-expression control), the permuted-control JSONs, all aggregated
statistics (results/statistics, minus legacy/obsolete copies), the six locally cached core dataset variants and the
small prepared post-cutoff tables, the paper source and figures, the datasheet PDF and the changelog.
Excluded (release assets instead): Parquet feature matrices, per-row judgment JSONs, *.bak backups, logs, the
74 MB salmonella table (regenerated by the preparation script) and the legacy expansion_gpt55_offline runs.

Usage: python scripts/release/build_supplement.py [--out paper/dmlr/supplement/dasef_supplement.zip]
"""
from __future__ import annotations

import argparse
import fnmatch
import os
import zipfile
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

INCLUDE_TREES = ["src", "scripts", "configs", "tests", "cache/schemas", "cache/schemas_anonymized", "cache/schemas_postcutoff_real",
                 "results/statistics", "paper/dmlr", "data/local_cache"]
INCLUDE_FILES = ["pyproject.toml", "requirements-lock.txt", "README.md", "LICENSE", "CHANGELOG.md", ".env.example"]
RUN_ROOTS = ["results/judgments", "results/expansion_offline", "results/postcutoff_real", "results/anonymized_control", "results/schema_runs",
             "results/full_suite_prospective"]
RUN_FILES = {"results.json", "schema.normalized.json", "dataset_summary.json", "run_plan.json", "run_plan.md", "completed_runs.json",
             "run_level_scores.csv", "run_level_scores_gen.csv", "rebuild.log"}
EXCLUDE_GLOBS = [
    "results/statistics/_pre_onehot_backup*",  # pre-correction backups (see CHANGELOG v1.1), not part of the release
    "*.pre-onehot.bak","results/*.parquet", "*.bak", "*.pyc", "__pycache__/*", "*.aux", "*.blg", "*.out", "*.log", "*.fls", "*.fdb_latexmk", "*.synctex.gz",
                 "*OBSOLETE*", "*legacy*", "*/postcutoff_salmonella_serovar_*/*", "*.docx", "*.png", "*/judgments/row_*.json",
                 "*/smoke/*", "*/xgboost_backfill/*", "paper/dmlr/supplement/*.zip", "paper/dmlr/main.pdf",
                 "paper/dmlr/SUBMISSION_CHECKLIST.md", "scripts/loo_stability_analysis.py", "scripts/gepa_*", "*.tar.gz",
                 "scripts/expansion/launch_expansion_gpt55.sh", "results/statistics/ANALYSIS_COMPLETE.md", "results/statistics/gemini31/*",
                 "results/statistics/clean_formula_controls_*", "results/statistics/prospective_formula_controls_*",
                 "results/statistics/downstream_awareness_*", "results/statistics/existing_result_stats_*",
                 "results/postcutoff_real/run_plan.*", "cache/schemas/bngtic_tac_toe/*", "cache/schemas/bngbreast_w/*",
                 "results/statistics/classical_baselines_onehot/*", "scripts/run_deepseek_judgment_shortlist.sh"]


def excluded(rel: str) -> bool:
    return any(fnmatch.fnmatch(rel, g) or fnmatch.fnmatch("/" + rel, "*/" + g) for g in EXCLUDE_GLOBS)


def collect() -> list[Path]:
    files: list[Path] = []
    for tree in INCLUDE_TREES:
        for p in (ROOT / tree).rglob("*"):
            if p.is_file() and not excluded(str(p.relative_to(ROOT))):
                files.append(p)
    for f in INCLUDE_FILES:
        if (ROOT / f).exists():
            files.append(ROOT / f)
    for root in RUN_ROOTS:
        for p in (ROOT / root).rglob("*"):
            if p.is_file() and p.name in RUN_FILES and not excluded(str(p.relative_to(ROOT))):
                files.append(p)
    # permuted-control JSONs of the expansion tier
    for p in (ROOT / "results/expansion_offline").rglob("*_permuted.json"):
        files.append(p)
    return sorted(set(files))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="paper/dmlr/supplement/dasef_supplement.zip")
    ap.add_argument("--limit-mb", type=float, default=100.0)
    args = ap.parse_args()
    files = collect()
    by_cat = defaultdict(int)
    total = 0
    for p in files:
        rel = p.relative_to(ROOT)
        cat = "/".join(rel.parts[:2]) if rel.parts[0] in ("results", "cache", "paper", "data") else rel.parts[0]
        by_cat[cat] += p.stat().st_size
        total += p.stat().st_size
    out = ROOT / args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(out, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for p in files:
            z.write(p, arcname=str(Path("dasef_supplement") / p.relative_to(ROOT)))
    zipped = out.stat().st_size
    print(f"files: {len(files)}  uncompressed: {total / 1e6:.1f} MB  zip: {zipped / 1e6:.1f} MB  -> {out}")
    for cat, sz in sorted(by_cat.items(), key=lambda kv: -kv[1]):
        print(f"  {sz / 1e6:8.1f} MB  {cat}")
    if zipped > args.limit_mb * 1e6:
        raise SystemExit(f"ZIP EXCEEDS {args.limit_mb} MB: move more to release assets")
    (out.with_suffix(".manifest.txt")).write_text("\n".join(str(p.relative_to(ROOT)) for p in files) + "\n")


if __name__ == "__main__":
    main()
